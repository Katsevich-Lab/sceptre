refactor_native_function <- function(name) {
    getFromNamespace(name, "sceptre")
}

refactor_native_bridge <- local({
    compiled <- NULL
    function(path) {
        if (is.null(compiled)) {
            environment <- new.env(parent = baseenv())
            Rcpp::sourceCpp(path, env = environment, rebuild = FALSE, showOutput = FALSE)
            compiled <<- environment
        }
        compiled
    }
})

refactor_native_run_case <- function(case, bridge) {
    stopifnot(
        is.integer(case$trt_idxs),
        all(case$trt_idxs >= 1L & case$trt_idxs <= length(case$a)),
        length(case$draws) == case$B1 + case$B2 + case$B3,
        all(lengths(case$draws) >= case$n_trt)
    )
    args <- case[setdiff(names(case), c("draws", "expected_stage", "expected_sn"))]
    args$synthetic_idxs <- bridge$refactor_native_pointer(case$draws, length(case$a))
    do.call(refactor_native_function("run_association_test"), args)
}

# Test the three samplers currently called by the package.
refactor_native_candidate_samplers <- function() {
    c(fisher_yates = "fisher_yates_sampler",
      hybrid = "hybrid_fisher_iwor_sampler",
      crt_fast_production = "sample_crt_indices")
}

refactor_native_sample <- function(config, candidate_name, bridge) {
    pointer <- do.call(refactor_native_function(candidate_name), config$args)
    # Read every draw generated by the installed package, not just used prefixes.
    bridge$refactor_native_materialize(pointer)
}

# Check sampling probabilities against elementary Bernoulli / sampling-without-
# replacement formulas. Six standard errors give a broad, fixed-seed tolerance;
# the one-draw allowance also handles probabilities exactly zero or one.
expect_sampler_probabilities <- function(draws, probabilities, pair_probability) {
    B <- length(draws)
    selected <- vapply(seq_along(probabilities) - 1L, function(cell) {
        vapply(draws, function(draw) cell %in% draw, logical(1))
    }, logical(B))
    within <- function(observed, expected, n) {
        all(abs(observed - expected) <=
                6 * sqrt(expected * (1 - expected) / n) + 1 / n)
    }
    expect_true(within(colMeans(selected), probabilities, B),
                info = "cell inclusion probabilities")
    pairs <- combn(seq_along(probabilities), 2L)
    observed <- colMeans(selected[, pairs[1L, ], drop = FALSE] &
                         selected[, pairs[2L, ], drop = FALSE])
    expect_true(within(observed, pair_probability(pairs), B),
                info = "joint inclusion probabilities within each draw")
    odd <- seq.int(1L, B - 1L, 2L)
    observed <- colMeans(selected[odd, , drop = FALSE] &
                         selected[odd + 1L, , drop = FALSE])
    expect_true(within(observed, probabilities^2, length(odd)),
                info = "independence between successive draws")
}
