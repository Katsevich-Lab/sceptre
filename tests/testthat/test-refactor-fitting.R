test_that("current fitters accept plain arrays without object or cache state", {
    y <- c(0, 1, 2, 0, 3, 5, 1, 2)
    design <- matrix(1, length(y), 1L, dimnames = list(NULL, "intercept"))
    treatment <- c(2L, 5L, 8L)
    before <- serialize(list(y, design, treatment), NULL)
    fit <- fit_response(y, design)
    expect_named(fit, c("fitted_coefs", "theta"))
    expect_equal(unname(fit$fitted_coefs), log(mean(y)), tolerance = 1e-10)
    expect_true(is.finite(fit$theta) && fit$theta >= 0.01 && fit$theta <= 1000)
    probability <- fit_assignment_probabilities(treatment, design)
    expect_equal(probability, rep(3 / 8, 8L), tolerance = 1e-10)
    expect_identical(serialize(list(y, design, treatment), NULL), before)
    expect_error(fit_response(y, cbind(design, design)),
                 "cannot be estimated in the regression model")
})

test_that("score preparation declares and preserves one ordered numeric view", {
    y <- c(0, 1, 3, 2, 0)
    design <- matrix(1, length(y), 1L)
    fit <- list(fitted_coefs = log(2), theta = 4)
    before <- serialize(list(y, design, fit), NULL)
    score <- prepare_score_components(y, design, fit)
    expect_named(score, c("mu", "w", "a", "D"))
    expect_equal(score$mu, rep(2, 5L))
    expect_equal(score$w, rep(4 / 3, 5L))
    expect_equal(score$a, (y - 2) / 1.5)
    expect_identical(dim(score$D), c(1L, 5L))
    expect_equal(unname(score$D), matrix(sqrt(4 / 15), 1L, 5L))
    expect_identical(serialize(list(y, design, fit), NULL), before)
})
